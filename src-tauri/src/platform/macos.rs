    #[test]
    fn cf_html_roundtrip() {
        let html = b"<b>Hello</b> world".to_vec();
        let cf = html_to_cf_html(html.clone());
        assert!(cf.starts_with(b"Version:0.9\r\n"));
        assert_eq!(cf_html_to_html(&cf), html);
    }
